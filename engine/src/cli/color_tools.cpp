int runColorTool(const std::vector<std::string>& args) {
  if (args.size() == 3 && args[0] == "make-cmyk-profile") {
    return makeCmykProfile(args[1], args[2]);
  }
  return -1;
}

void printColorToolUsage() {
  std::fprintf(stderr, "  nanquim-cli make-cmyk-profile <input CMYK.icc> <output.icc>\n");
}

