def clean(fields):
    return {key: clean(value) if isinstance(value, dict) else value
            for key, value in fields.items() if "." not in key}


def default_size(document):
    limits = document.get("limits", {})
    minimum, maximum = limits.get("minSize", 1), limits.get("maxSize", 500)
    slider = document.get("defaults", {}).get("size", 0.3)
    return minimum + (maximum - minimum) * slider * slider


def golden_scene(group, documents):
    row_height = 64
    width = 768
    actions = []
    for row, (brush_dir, document) in enumerate(documents):
        y0 = row_height * row + row_height / 2
        samples = []
        for index in range(121):
            t = index / 120
            samples.append([round(32 + (width - 64) * t, 3), round(y0 + 12 * math.sin(2 * math.pi * t), 3),
                            round(0.15 + 0.85 * math.sin(math.pi * t), 4), round(index * 4.0, 1)])
        actions.append({"type": "stroke", "tool": "paint", "layer": 1, "size": round(min(default_size(document), 40), 3),
                        "opacity": 1, "color": [0.1, 0.1, 0.12, 1], "brushPackage": brush_dir, "samples": samples})
    return {"format": 1, "documentId": f"golden-library-{group}",
            "canvas": {"width": width, "height": row_height * len(documents), "background": [1, 1, 1, 1]},
            "layers": 1, "actions": actions}


def main() -> int:
    cli = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_CLI
    if not cli.exists() and cli.with_suffix(".exe").exists():
        cli = cli.with_suffix(".exe")
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    groups = {}
    credit_rows = []
    for group in GROUP_ORDER:
        groups[group] = []
        documents = []
        for fields, textures in LIBRARY[group]:
            fields = clean(fields)
            identifier = brush_id(group, fields["name"])
            folder = OUTPUT / group / identifier
            folder.mkdir(parents=True)
            document = {"format": 1, "id": identifier, "name": fields["name"], **AUTHOR}
            document.update({key: value for key, value in fields.items() if key != "name"})
            (folder / "brush.json").write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
            relative = folder.relative_to(REPOSITORY_ROOT).as_posix()
            credit_rows.append(f"| `{relative}/brush.json` | Nanquim contributors | Brush parameters ({fields['name']}) | MIT |")
            for file_name, (kind, size, seed, parameter) in textures.items():
                subprocess.run([str(cli), "texture", kind, str(size), str(seed), str(parameter), str(folder / file_name)],
                               check=True)
                credit_rows.append(
                    f"| `{relative}/{file_name}` | Nanquim contributors | Procedural: `{kind} {size} {seed} {parameter}` | MIT |"
                )
            groups[group].append(identifier)
            documents.append((f"../../assets-src/brushes/{group}/{identifier}", document))
        scene = golden_scene(group, documents)
        (GOLDEN_SCENES / f"library_{group}.json").write_text(json.dumps(scene) + "\n", encoding="utf-8")
    library = {
        "format": 1,
        "version": LIBRARY_VERSION,
        "defaults": {tool: brush_id(*key) for tool, key in DEFAULTS.items()},
        "groups": [{"key": key, "brushes": groups[key]} for key in GROUP_ORDER],
    }
    (OUTPUT / "library.json").write_text(json.dumps(library, indent=2) + "\n", encoding="utf-8")
    credit_rows.insert(0, "| `assets-src/brushes/library.json` | Nanquim contributors | Built-in library order | MIT |")
    write_credits(credit_rows)
    total = sum(len(brushes) for brushes in groups.values())
    print(f"wrote {total} brushes to {OUTPUT.relative_to(REPOSITORY_ROOT)} and {len(GROUP_ORDER)} golden scenes")
    return 0


