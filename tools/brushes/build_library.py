def brush_id(group, name):
    return FIXED_IDS.get((group, name)) or str(uuid.uuid5(ID_NAMESPACE, f"nanquim/brush/{group}/{name}"))


def merge(base, extra):
    result = json.loads(json.dumps(base))
    for key, value in extra.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = merge(result[key], value)
        else:
            result[key] = value
    return result


def taper(start, end, minimum=0.1, shape=0.0):
    settings = {"start": start, "end": end, "minSize": minimum, "shape": shape}
    return {"taper": {"stylus": settings, "finger": settings}}


